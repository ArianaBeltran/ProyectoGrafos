class Arista {

    constructor(
        origen,
        destino,
        pesoIda,
        pesoVuelta,
        dirigida,
        bidireccional
    ) {

        this.origen = origen;

        this.destino = destino;

        this.pesoIda = pesoIda;

        this.pesoVuelta = pesoVuelta;

        this.dirigida = dirigida;

        this.bidireccional =
            bidireccional;

    }

}